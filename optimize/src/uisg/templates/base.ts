import type { UisgSurface, UisgGraph } from '../types.js';
import type { TemplateTarget } from './render.js';
import type { TemplateShape } from './index.js';
import { renderTargetComponent, renderTargetTest } from './render.js';

export interface BaseTemplateOptions {
  shape: TemplateShape;
  name: string;
  description: string;
  defaultImports?: string[];
  defaultTestImports?: string[];
  defaultTestMocks?: string[];
  defaultTestWrapperStart?: string;
  defaultTestWrapperEnd?: string;
}

export abstract class BaseTemplate {
  readonly shape: TemplateShape;
  readonly name: string;
  readonly description: string;
  public readonly defaultImports: string[];
  public readonly defaultTestImports: string[];
  public readonly defaultTestMocks: string[];
  public readonly defaultTestWrapperStart: string;
  public readonly defaultTestWrapperEnd: string;

  constructor(options: BaseTemplateOptions) {
    this.shape = options.shape;
    this.name = options.name;
    this.description = options.description;
    this.defaultImports = options.defaultImports ?? [
      'import React from \'react\';',
      'import { cn } from \'../../utils/ui\';',
    ];
    this.defaultTestImports = options.defaultTestImports ?? [
      'import { render, screen, fireEvent } from \'@testing-library/react\';',
      'import { describe, it, expect, vi } from \'vitest\';',
    ];
    this.defaultTestMocks = options.defaultTestMocks ?? [];
    this.defaultTestWrapperStart = options.defaultTestWrapperStart ?? '';
    this.defaultTestWrapperEnd = options.defaultTestWrapperEnd ?? '';
  }

  public deriveComponentName(surface: UisgSurface): string {
    return surface.component ?? surface.id.replace('surface.', '').replace(/-./g, (m: string) => m[1].toUpperCase());
  }

  public deriveTestId(surface: UisgSurface): string {
    return this.deriveComponentName(surface).replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
  }

  public getCategoryPath(surface: UisgSurface): string {
    return (surface as any).category ?? '';
  }

  public getImportPath(surface: UisgSurface): string {
    const componentName = this.deriveComponentName(surface);
    const category = this.getCategoryPath(surface);
    if (category) {
      return `../../components/${category}/${componentName}`;
    }
    return `../../components/${componentName}`;
  }

  public getPropsSchemaImport(surface: UisgSurface): string {
    const componentName = this.deriveComponentName(surface);
    return `import { ${componentName}Props } from './${componentName}Props';`;
  }

  public generateHeader(surface: UisgSurface): string {
    return `// GENERATED by optimize/src/uisg/codegen.ts
// DO NOT EDIT MANUALLY
// Template: ${this.name}
// Source surface: ${surface.id}
`;
  }

  public getCommonImports(surface: UisgSurface, target: TemplateTarget): string[] {
    if (target !== 'react') return [];
    return [...this.defaultImports];
  }

  public getTestImports(surface: UisgSurface, target: TemplateTarget): string[] {
    if (target !== 'react') return [];
    const imports = [...this.defaultTestImports];
    const importPath = this.getImportPath(surface);
    imports.unshift(`import { ${this.deriveComponentName(surface)} } from '${importPath}';`);
    return imports;
  }

  public getTestMocks(surface: UisgSurface, target: TemplateTarget): string[] {
    if (target !== 'react') return [];
    return this.defaultTestMocks;
  }

  public getTestWrapper(surface: UisgSurface, target: TemplateTarget): { start: string; end: string } {
    if (target !== 'react') return { start: '', end: '' };
    return { start: this.defaultTestWrapperStart, end: this.defaultTestWrapperEnd };
  }

  abstract generateComponent(surface: UisgSurface, graph: UisgGraph, target: TemplateTarget): string;
  abstract generateTest(surface: UisgSurface, graph: UisgGraph, target: TemplateTarget): string;
  abstract generatePropsSchema(surface: UisgSurface, graph: UisgGraph): string;

  // Template method for non-React targets
  public generateNonReactComponent(surface: UisgSurface, target: TemplateTarget): string {
    return renderTargetComponent(surface, this.shape, target);
  }

  public generateNonReactTest(surface: UisgSurface, target: TemplateTarget): string {
    return renderTargetTest(surface, this.deriveComponentName(surface), target);
  }
}

