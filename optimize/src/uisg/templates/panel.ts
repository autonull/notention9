import type { Template } from './index.js';
import { renderTargetComponent, renderTargetTest, type TemplateTarget } from './render.js';

export const panelTemplate: Template = {
    shape: 'panel',
    name: 'panel',
    description: 'Collapsible sidebar/rail with tabs, lists, and content sections',

    generateComponent(surface: any, graph: any, target: TemplateTarget): string {
        if (target !== 'react') return renderTargetComponent(surface, 'panel', target);
        const componentName = surface.component ?? surface.id.replace('surface.', '').replace(/-./g, (m: string) => m[1].toUpperCase());
        const testId = componentName.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

        return `// GENERATED by optimize/src/uisg/codegen.ts
// DO NOT EDIT MANUALLY
// Template: panel
// Source surface: ${surface.id}

import React, { useMemo, useState, useCallback } from 'react';
import { cn } from '../../utils/ui';
import { Tabs } from '../ui/kit';
import { Button } from '../ui/Button';
import { Input } from '../ui/Input';
import type { Note, ScoredMatch, Contact } from '@notention/core';

interface ${componentName}Props {
    /** Primary content to render in the panel */
    content?: React.ReactNode;
    /** Optional title for the panel */
    title?: string;
    /** Whether the panel is open */
    isOpen?: boolean;
    /** Callback when panel open state changes */
    onOpenChange?: (open: boolean) => void;
    /** Tab configuration */
    tabs?: Array<{ id: string; label: string; count?: number; icon?: React.ReactNode }>;
    /** Active tab ID */
    activeTab?: string;
    /** Callback when tab changes */
    onTabChange?: (tabId: string) => void;
    /** Items to render in list tabs (e.g., matches, replies) */
    items?: Array<{ id: string; title?: string; subtitle?: string; onClick?: () => void }>;
    /** Empty state message */
    emptyMessage?: string;
    /** Additional CSS classes */
    className?: string;
    /** Test ID for the panel root */
    testId?: string;
}

const DEFAULT_TABS: Array<{ id: string; label: string; count?: number; icon?: React.ReactNode }> = [
    { id: 'content', label: 'Content' },
    { id: 'list', label: 'List' },
];

export function ${componentName}({
    content,
    title,
    isOpen = true,
    onOpenChange,
    tabs = DEFAULT_TABS,
    activeTab,
    onTabChange,
    items = [],
    emptyMessage = 'No items to display.',
    className,
    testId = '${testId}',
}: ${componentName}Props) {
    const [localOpen, setLocalOpen] = useState(isOpen);
    const [localActiveTab, setLocalActiveTab] = useState(activeTab ?? tabs[0]?.id ?? 'content');
    const [filterText, setFilterText] = useState('');

    const isControlled = activeTab !== undefined;
    const open = isOpen ?? localOpen;
    const currentTab = isControlled ? activeTab : localActiveTab;

    const handleOpenChange = useCallback((nextOpen: boolean) => {
        if (isOpen === undefined) setLocalOpen(nextOpen);
        onOpenChange?.(nextOpen);
    }, [isOpen, onOpenChange]);

    const handleTabChange = useCallback((nextTab: string) => {
        if (!isControlled) setLocalActiveTab(nextTab);
        onTabChange?.(nextTab);
    }, [isControlled, onTabChange]);

    const filteredItems = useMemo(() => {
        if (!filterText) return items;
        const lower = filterText.toLowerCase();
        return items.filter(item =>
            item.title?.toLowerCase().includes(lower) ||
            item.subtitle?.toLowerCase().includes(lower)
        );
    }, [items, filterText]);

    const isEmpty = filteredItems.length === 0;

    let panelContent: React.ReactNode;
    if (content && currentTab === 'content') {
        panelContent = <div data-testid={testId + '-content'}>{content}</div>;
    } else if (currentTab === 'list') {
        if (isEmpty) {
            panelContent = (
                <div data-testid={testId + '-list'}>
                    <div className="flex items-center justify-center h-24 text-[12px] text-[var(--app-muted)]">
                        {emptyMessage}
                    </div>
                </div>
            );
        } else {
            panelContent = (
                <div data-testid={testId + '-list'}>
                    <div className="space-y-1">
                        {filteredItems.map(item => (
                            <button
                                key={item.id}
                                type="button"
                                onClick={item.onClick}
                                className="w-full rounded-lg border border-[var(--app-line)] bg-[var(--app-surface)] p-2 text-left transition-colors hover:border-[var(--app-line-strong)]"
                                data-testid={testId + '-item-' + item.id}
                            >
                                {item.title && (
                                    <div className="truncate text-[12px] font-medium text-[var(--app-text-secondary)]">
                                        {item.title}
                                    </div>
                                )}
                                {item.subtitle && (
                                    <div className="mt-0.5 line-clamp-2 text-[11px] leading-4 text-[var(--app-muted)]">
                                        {item.subtitle}
                                    </div>
                                )}
                            </button>
                        ))}
                    </div>
                </div>
            );
        }
    } else {
        panelContent = <div data-testid={testId + '-tab-' + currentTab}>{content}</div>;
    }

    if (!open) {
        return (
            <Button
                variant="ghost"
                size="sm"
                onClick={() => handleOpenChange(true)}
                data-testid={testId + '-toggle'}
                aria-label={\`Open \${title ?? 'panel'}\`}
            >
                {title ?? 'Open panel'}
            </Button>
        );
    }

    return (
        <aside
            className={cn(
                'flex h-full min-h-0 flex-col bg-[var(--app-panel)] border-l border-[var(--app-line)]',
                className
            )}
            data-testid={testId}
            aria-label={title}
        >
            {(title || tabs.length > 1) && (
                <div className="flex items-center justify-between shrink-0 border-b border-[var(--app-line)] px-2 py-1.5">
                    {title && (
                        <h3 className="text-[12px] font-semibold text-[var(--app-text-secondary)] truncate">
                            {title}
                        </h3>
                    )}
                    {tabs.length > 1 && (
                        <Tabs<string>
                            options={tabs.map(t => ({ id: t.id, label: t.label, count: t.count }))}
                            value={currentTab}
                            onChange={handleTabChange}
                            label={title ?? 'Panel tabs'}
                            size="sm"
                            className="h-8"
                        />
                    )}
                </div>
            )}

            <div className="min-h-0 flex-1 overflow-y-auto p-2 custom-scrollbar">
                {currentTab === 'list' && items.length > 0 && (
                    <div className="mb-2">
                        <label className="sr-only" htmlFor={testId + '-filter'}>Filter items</label>
                        <Input
                            id={testId + '-filter'}
                            value={filterText}
                            onChange={e => setFilterText(e.target.value)}
                            placeholder="Filter…"
                            className="max-w-xs"
                        />
                    </div>
                )}

                {panelContent}
            </div>
        </aside>
    );
}
`;
    },

    generateTest(surface: any, graph: any, target: TemplateTarget): string {
        const componentName = surface.component ?? surface.id.replace('surface.', '').replace(/-./g, (m: string) => m[1].toUpperCase());
        if (target !== 'react') return renderTargetTest(surface, componentName, target);
        const testId = componentName.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

        return `// GENERATED by optimize/src/uisg/codegen.ts
// DO NOT EDIT MANUALLY
// Template: panel
// Source surface: ${surface.id}

import { describe, it, expect, vi } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { ${componentName} } from '@/components/panels/${componentName}';
import type { Note, ScoredMatch, Contact } from '@notention/core';

const mockItems = [
    { id: '1', title: 'Item One', subtitle: 'First item', onClick: vi.fn() },
    { id: '2', title: 'Item Two', subtitle: 'Second item', onClick: vi.fn() },
    { id: '3', title: 'Third Item', subtitle: 'Another item', onClick: vi.fn() },
];

const mockTabs = [
    { id: 'content', label: 'Content', count: 0 },
    { id: 'list', label: 'List', count: 3 },
];

describe('${componentName} (generated)', () => {
    it('renders panel with title', () => {
        render(<${componentName} title="Test Panel" />);
        expect(screen.getByTestId('${testId}')).toBeInTheDocument();
        expect(screen.getByText('Test Panel')).toBeInTheDocument();
    });

    it('renders tabs when provided', () => {
        render(<${componentName} tabs={mockTabs} />);
        expect(screen.getByText('Content')).toBeInTheDocument();
        expect(screen.getByText('List')).toBeInTheDocument();
    });

    it('switches tabs on click', () => {
        render(<${componentName} tabs={mockTabs} />);
        const listTab = screen.getByRole('tab', { name: /List/i });
        fireEvent.click(listTab);
        expect(screen.getByTestId('${testId}-list')).toBeInTheDocument();
    });

    it('renders items in list tab', () => {
        render(<${componentName} tabs={mockTabs} activeTab="list" items={mockItems} />);
        expect(screen.getByText('Item One')).toBeInTheDocument();
        expect(screen.getByText('Item Two')).toBeInTheDocument();
    });

    it('filters items by text', () => {
        render(<${componentName} tabs={mockTabs} activeTab="list" items={mockItems} />);
        const filterInput = screen.getByPlaceholderText('Filter…');
        fireEvent.change(filterInput, { target: { value: 'One' } });
        expect(screen.getByText('Item One')).toBeInTheDocument();
        expect(screen.queryByText('Item Two')).not.toBeInTheDocument();
    });

    it('shows empty message when no items', () => {
        render(<${componentName} tabs={mockTabs} activeTab="list" items={[]} emptyMessage="Nothing here" />);
        expect(screen.getByText('Nothing here')).toBeInTheDocument();
    });

    it('collapses when isOpen is false', () => {
        render(<${componentName} isOpen={false} title="Collapsible" />);
        expect(screen.getByText('Collapsible')).toBeInTheDocument();
    });

    it('calls onTabChange when tab changes', () => {
        const onTabChange = vi.fn();
        render(<${componentName} tabs={mockTabs} onTabChange={onTabChange} />);
        const listTab = screen.getByRole('tab', { name: /List/i });
        fireEvent.click(listTab);
        expect(onTabChange).toHaveBeenCalledWith('list');
    });

    it('calls onOpenChange when toggled', () => {
        const onOpenChange = vi.fn();
        render(<${componentName} isOpen={false} onOpenChange={onOpenChange} title="Toggle" />);
        fireEvent.click(screen.getByText('Toggle'));
        expect(onOpenChange).toHaveBeenCalledWith(true);
    });

    it('has proper accessibility attributes', () => {
        render(<${componentName} title="Accessible Panel" />);
        const panel = screen.getByTestId('${testId}');
        expect(panel).toHaveAttribute('aria-label', 'Accessible Panel');
    });
});
`;
    },

    generatePropsSchema(surface: any, graph: any): string {
        return `// GENERATED by optimize/src/uisg/codegen.ts
// DO NOT EDIT MANUALLY
// Template: panel
// Source surface: ${surface.id}

import { z } from 'zod';

export const ${surface.id.replace(/[.-]/g, '_')}_PropsSchema = z.object({
    content: z.any().optional(),
    title: z.string().optional(),
    isOpen: z.boolean().optional(),
    onOpenChange: z.function().args(z.boolean()).returns(z.void()).optional(),
    tabs: z.array(z.object({
        id: z.string(),
        label: z.string(),
        count: z.number().optional(),
        icon: z.any().optional(),
    })).optional(),
    activeTab: z.string().optional(),
    onTabChange: z.function().args(z.string()).returns(z.void()).optional(),
    items: z.array(z.object({
        id: z.string(),
        title: z.string().optional(),
        subtitle: z.string().optional(),
        onClick: z.function().returns(z.void()).optional(),
    })).optional(),
    emptyMessage: z.string().optional(),
    className: z.string().optional(),
    testId: z.string().optional(),
});

export type ${surface.id.replace(/[.-]/g, '_').replace(/-./g, (m: string) => m[1].toUpperCase())}Props = z.infer<typeof ${surface.id.replace(/[.-]/g, '_')}_PropsSchema>;
`;
    },
};