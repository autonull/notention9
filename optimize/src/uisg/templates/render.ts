import type { UisgSurface } from '../types.js';

export type TemplateTarget = 'react' | 'html' | 'json';

export const TARGET_EXTENSION: Record<TemplateTarget, string> = {
    react: '.tsx',
    html: '.html',
    json: '.json',
};

const ESCAPES: Record<string, string> = {
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
};

const escapeHtml = (value: string): string => value.replace(/[&<>"']/g, char => ESCAPES[char]);

export function renderTargetComponent(surface: UisgSurface, shape: string, target: TemplateTarget): string {
    if (target === 'html') {
        return `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>${escapeHtml(surface.name)}</title></head>
<body data-uisg-surface="${escapeHtml(surface.id)}" data-uisg-shape="${shape}">
    <main>
        <h1>${escapeHtml(surface.name)}</h1>
        <p>${escapeHtml(surface.summary ?? '')}</p>
        <pre>${escapeHtml(JSON.stringify(surface.propsSchema ?? {}, null, 2))}</pre>
    </main>
</body>
</html>
`;
    }
    if (target === 'json') {
        return JSON.stringify({
            surface: surface.id,
            name: surface.name,
            shape,
            route: surface.route,
            propsSchema: surface.propsSchema ?? {},
            variants: surface.variants ?? {},
            defaultVariant: surface.defaultVariant,
        }, null, 2) + '\n';
    }
    throw new Error(`Unsupported component target: ${target}`);
}

export function renderTargetTest(surface: UisgSurface, componentName: string, target: TemplateTarget): string {
    if (target === 'html') {
        return `// GENERATED by optimize/src/uisg/codegen.ts
import { readFileSync } from 'node:fs';
import { expect, test } from 'vitest';

test('${surface.id} html artifact', () => {
    const html = readFileSync(new URL('../../generated/html/${componentName}.html', import.meta.url), 'utf8');
    expect(html).toContain('data-uisg-surface="${surface.id}"');
});
`;
    }
    if (target === 'json') {
        return `// GENERATED by optimize/src/uisg/codegen.ts
import { readFileSync } from 'node:fs';
import { expect, test } from 'vitest';

test('${surface.id} json artifact', () => {
    const schema = JSON.parse(readFileSync(new URL('../../generated/json/${componentName}.json', import.meta.url), 'utf8'));
    expect(schema.surface).toBe('${surface.id}');
});
`;
    }
    throw new Error(`Unsupported test target: ${target}`);
}
