import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const THEMES_FILE = resolve(ROOT, 'doc/uisg/themes.json');
const STYLES_DIR = resolve(ROOT, 'ui/src/styles');

const themesFile = (): string => process.env.NOTENTION_UISG_THEMES ?? THEMES_FILE;
const stylesDir = (): string => process.env.NOTENTION_UISG_STYLES_DIR ?? STYLES_DIR;

export interface ThemeTokens {
    accent: string;
    radius: string;
    font: string;
}

export type ThemesData = Record<string, ThemeTokens>;

export interface ThemeSummary extends ThemeTokens {
    id: string;
}

let _cachedThemes: ThemesData | null = null;
let _cachedThemesPath: string | null = null;

export function loadThemes(): ThemesData {
    const path = themesFile();
    if (_cachedThemes && _cachedThemesPath === path) {
        return _cachedThemes;
    }
    _cachedThemes = JSON.parse(readFileSync(path, 'utf8')) as ThemesData;
    _cachedThemesPath = path;
    return _cachedThemes;
}

export function listThemes(): ThemeSummary[] {
    return Object.entries(loadThemes()).map(([id, tokens]) => ({ id, ...tokens }));
}

export function getTheme(id: string): ThemeTokens {
    const theme = loadThemes()[id];
    if (!theme) throw new Error(`Unknown theme: ${id}`);
    return theme;
}

export function themeCssPath(id: string): string {
    return resolve(stylesDir(), `theme-${id}.css`);
}

export function emitThemeCss(id: string, tokens: ThemeTokens): string {
    return `/* AUTO-GENERATED by \`pnpm uisg themes generate ${id}\` from doc/uisg/themes.json. Do not edit. */
:root {
    --accent-color: ${tokens.accent};
    --theme-radius: ${tokens.radius};
    --theme-font: ${tokens.font};
}
`;
}

export function writeThemeCss(id: string): string {
    const path = themeCssPath(id);
    writeFileSync(path, emitThemeCss(id, getTheme(id)));
    return path;
}
