import { edgesFrom, indexGraph } from './query.js';
import type { SkeletonEffect } from './skeleton.js';
import type { UisgEffect, UisgGraph, UisgPredicate, UisgStep } from './types.js';

export interface FlowReducer {
    states: Record<string, { guards: string[]; effects: string[]; transitions: Array<{ when?: string; to: string }> }>;
    initial: string;
}

function effectsOf(index: ReturnType<typeof indexGraph>, step: UisgStep): SkeletonEffect[] {
    return edgesFrom(index, step.id, 'invokes')
        .flatMap(({ to }) => edgesFrom(index, to, 'effects'))
        .map(({ to }) => index.byId.get(to))
        .filter((node): node is UisgEffect => node?.type === 'effect')
        .map(node => ({
            id: node.id, name: node.name, risk: node.risk,
            reversibility: node.reversibility, confirmationRequired: node.confirmationRequired,
        }))
        .filter((effect, position, all) => all.findIndex(({ id }) => id === effect.id) === position)
        .sort((a, b) => a.id.localeCompare(b.id));
}

function guardsOf(index: ReturnType<typeof indexGraph>, step: UisgStep): string[] {
    return edgesFrom(index, step.id, 'guards')
        .map(({ to }) => index.byId.get(to))
        .filter((guard): guard is UisgPredicate => guard?.type === 'predicate')
        .map(guard => guard.id)
        .sort();
}

function transitionsOf(index: ReturnType<typeof indexGraph>, step: UisgStep): Array<{ when?: string; to: string }> {
    return edgesFrom(index, step.id, 'next')
        .map(({ to, when }) => ({ to, when: when ?? undefined }))
        .sort((a, b) => a.to.localeCompare(b.to));
}

export function flowToReducer(graph: UisgGraph, flowId: string): FlowReducer {
    const index = indexGraph(graph);
    const flow = index.byId.get(flowId);
    if (flow?.type !== 'flow') {
        throw new Error(`Flow not found: ${flowId}`);
    }

    const contained = new Set(edgesFrom(index, flowId, 'contains').map(({ to }) => to));
    const states: Record<string, { guards: string[]; effects: string[]; transitions: Array<{ when?: string; to: string }> }> = {};
    const visited = new Set<string>();
    let current: string | undefined = flow.entry;

    while (current) {
        if (visited.has(current)) {
            throw new Error(`Cycle detected at ${current} in flow ${flowId}`);
        }
        visited.add(current);
        const node = index.byId.get(current);
        if (node?.type !== 'step' || !contained.has(current)) {
            throw new Error(`Step ${current} is not contained in ${flowId}`);
        }

        states[node.id] = {
            guards: guardsOf(index, node),
            effects: effectsOf(index, node).map(e => e.id),
            transitions: transitionsOf(index, node),
        };

        const branches = edgesFrom(index, current, 'next');
        if (!branches.length) break;

        current = branches.length === 1
            ? branches[0].to
            : undefined; // Will be resolved at runtime based on conditions
    }

    return { states, initial: flow.entry };
}

export function emitReducer(reducer: FlowReducer): string {
    const statesEntries = Object.entries(reducer.states).map(([stateId, state]) => {
        const guards = state.guards.map(id => JSON.stringify(id)).join(', ');
        const effects = state.effects.map(id => JSON.stringify(id)).join(', ');
        const transitions = state.transitions.map(t => 
            `{ to: ${JSON.stringify(t.to)}${t.when ? `, when: ${JSON.stringify(t.when)}` : ''} }`
        ).join(', ');
        return `  ${JSON.stringify(stateId)}: { guards: [${guards}], effects: [${effects}], transitions: [${transitions}] }`;
    }).join(',\n');

    return `// GENERATED by optimize/src/uisg/flowToReducer.ts
// DO NOT EDIT MANUALLY
// Source flow: ${reducer.initial.split('.')[0]} (${reducer.initial})

export interface FlowReducer {
    states: Record<string, { guards: string[]; effects: string[]; transitions: Array<{ when?: string; to: string }> }>;
    initial: string;
}

export const reducer: FlowReducer = {
    states: {
${statesEntries}
    },
    initial: ${JSON.stringify(reducer.initial)},
} satisfies FlowReducer;
`;
}

export function generateReducerFile(graph: UisgGraph, flowId: string, outputPath: string): void {
    const reducer = flowToReducer(graph, flowId);
    const content = emitReducer(reducer);
    const { writeFileSync, mkdirSync } = require('node:fs');
    const { dirname } = require('node:path');
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, content);
}