/**
 * Static analysis pass: scan ui/src/strategies/strategyConfigs.ts → emit seam-definitions.json
 * Content-addressed, hash-verified (S3)
 * 
 * Run with: pnpm generate:definitions
 * This script imports the core strategy params and UI component map.
 */

import { 
    getProjectRoot, 
    canonicalize, 
    shortSha256, 
    getGeneratedDir, 
    getSeamDefinitionsPath,
    writeJsonFile 
} from '../core/src/utils/common.js';
import { join } from 'node:path';
import { writeFileSync } from 'node:fs';
import type { ParamSpec, ParamDef as CoreParamDef } from '../core/src/ui/strategy.js';
import type { 
    SeamDefinition as CoreSeamDefinition, 
    EvaluatorConfig as CoreEvaluatorConfig,
    GovernanceLevel,
    EvidenceClass
} from '../core/src/schemas/seamDefinition.js';

const PROJECT_ROOT = getProjectRoot(import.meta.url);
const OUTPUT_DIR = getGeneratedDir(import.meta.url);
const OUTPUT_FILE = getSeamDefinitionsPath(import.meta.url);

// Re-use types from core schemas (single source of truth)
type ParamDef = CoreParamDef;
type EvaluatorConfig = CoreEvaluatorConfig;

interface StrategyInfo {
    id: string;
    seamId: string;
    seamName: string;
    seamRole: string;
    version: string;
    componentPath: string;
    componentName: string;
    paramSpec: Record<string, ParamDef>;
    defaultProps: Record<string, unknown>;
}

// SeamDefinition is imported from core schemas
type SeamDefinition = CoreSeamDefinition;

interface SeamDefinitionsOutput {
    version: 1;
    generatedAt: string;
    hash: string;
    strategies: StrategyInfo[];
    seams: SeamDefinition[];
}

function getEvaluatorForRole(role: string): EvaluatorConfig {
    if (role === 'capture' || role === 'elicit') {
        return {
            type: 'extraction',
            qualityFamily: 'extraction',
            metrics: ['precision', 'recall', 'f1'],
            primaryMetric: 'f1',
            mde: { f1: 0.05 },
            floors: { f1: 0.7 },
        };
    }
    if (role === 'match') {
        return {
            type: 'match',
            qualityFamily: 'match',
            metrics: ['recall', 'precision', 'f1'],
            primaryMetric: 'f1',
            mde: { f1: 0.05 },
            floors: { f1: 0.6 },
        };
    }
    return {
        type: 'custom',
        metrics: [],
        primaryMetric: '',
    };
}

// --- Main ---

async function main() {
    console.log('🔍 Loading strategy configs...');

    // Import core strategy params (source for generation)
    const { STRATEGY_PARAM_CONFIGS } = await import('../core/src/constants/strategyParams.js');
    const { BUILTIN_SEAM_SPECS, getAllBuiltinSeamSpecs } = await import('../core/src/constants/seams.js');

    // Import UI component map
    const { componentMap } = await import('../ui/src/strategies/componentMap.js');

    console.log(`Found ${STRATEGY_PARAM_CONFIGS.length} strategy configs`);
    console.log(`Found ${Object.keys(BUILTIN_SEAM_SPECS).length} builtin seam specs`);

    const strategies: StrategyInfo[] = [];

    for (const config of STRATEGY_PARAM_CONFIGS) {
        const paramSpec: Record<string, ParamDef> = {};

        for (const [key, def] of Object.entries(config.paramSpec)) {
            paramSpec[key] = {
                type: def.type,
                description: def.description,
                required: def.required,
                default: def.default,
                options: def.options,
                min: def.min,
                max: def.max,
            };
        }

        const componentInfo = componentMap[config.id];

        strategies.push({
            id: config.id,
            seamId: config.seam.id,
            seamName: config.seam.name,
            seamRole: config.seam.role,
            version: config.version,
            componentPath: componentInfo?.path ?? '',
            componentName: componentInfo?.name ?? '',
            paramSpec,
            defaultProps: config.defaultProps,
        });
    }

    // Build seam definitions from strategies
    const seams = buildSeamDefinitions(strategies, BUILTIN_SEAM_SPECS);
    console.log(`Built ${seams.length} seam definitions`);

    const output: SeamDefinitionsOutput = {
        version: 1,
        generatedAt: new Date().toISOString(),
        hash: '',
        strategies,
        seams,
    };

    // Compute content hash
    output.hash = shortSha256(canonicalize({ version: 1, generatedAt: output.generatedAt, strategies, seams }));

    // Write JSON output
    writeJsonFile(OUTPUT_FILE, output);
    console.log(`✅ Written to ${OUTPUT_FILE}`);
    console.log(`   Hash: ${output.hash}`);
    console.log(`   Strategies: ${output.strategies.length}`);
    console.log(`   Seams: ${output.seams.length}`);

    // Also write a TypeScript version for type safety
    const tsOutputFile = join(OUTPUT_DIR, 'seam-definitions.ts');
    const tsContent = `// Auto-generated by scripts/generate-definitions.ts
// DO NOT EDIT MANUALLY

import type { SeamDefinition } from '@notention/core/schemas';

export const SEAM_DEFINITIONS: SeamDefinition[] = ${JSON.stringify(seams, null, 4)};

export const STRATEGY_CONFIGS = ${JSON.stringify(strategies, null, 4)};
`;
    writeFileSync(tsOutputFile, tsContent, 'utf-8');
    console.log(`✅ TypeScript definitions written to ${tsOutputFile}`);
}

function buildSeamDefinitions(
    strategies: StrategyInfo[],
    builtinSeamSpecs: Record<string, any>
): SeamDefinition[] {
    const seamMap = new Map<string, {
        id: string;
        name: string;
        description: string;
        role: string;
        propsShape: Record<string, string>;
        components: Set<string>;
        paramSpecs: Map<string, Record<string, ParamDef>>;
        evaluator: EvaluatorConfig;
        governanceLevel: GovernanceLevel;
        evidenceClasses: EvidenceClass[];
    }>();

    for (const strat of strategies) {
        let seam = seamMap.get(strat.seamId);
        if (!seam) {
            // Get description and propsShape from builtin specs
            const builtin = builtinSeamSpecs[strat.seamId];
            const description = builtin?.description || `${strat.seamRole} seam`;
            const propsShape = builtin?.propsShape || {};

            // Default evaluator based on role
            const evaluator = getEvaluatorForRole(strat.seamRole);

            seam = {
                id: strat.seamId,
                name: strat.seamName,
                description,
                role: strat.seamRole,
                propsShape,
                components: new Set(),
                paramSpecs: new Map(),
                evaluator,
                governanceLevel: 'config' as GovernanceLevel,
                evidenceClasses: ['measured', 'observed'] as EvidenceClass[],
            };
            seamMap.set(strat.seamId, seam);
        }

        // Merge paramSpecs for this strategy
        seam.paramSpecs.set(strat.id, strat.paramSpec);

        // Add component name if available
        if (strat.componentName) {
            seam.components.add(strat.componentName);
        }
    }

    const now = new Date().toISOString();

    return Array.from(seamMap.values()).map(seam => {
        // Merge all paramSpecs for this seam
        const mergedParamSpec: Record<string, ParamDef> = {};
        for (const [_, ps] of seam.paramSpecs) {
            Object.assign(mergedParamSpec, ps);
        }

        return {
            id: seam.id,
            name: seam.name,
            description: seam.description,
            role: seam.role,
            propsShape: seam.propsShape,
            components: Array.from(seam.components),
            paramSpec: mergedParamSpec,
            evaluator: seam.evaluator,
            governanceLevel: seam.governanceLevel,
            evidenceClasses: seam.evidenceClasses,
            version: '1.0.0',
            createdAt: now,
            updatedAt: now,
        };
    });
}

main().catch(err => {
    console.error('❌ Generation failed:', err);
    process.exit(1);
});