import fs from 'fs/promises';
import path from 'path';
import {fileURLToPath} from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const OUTPUT = path.join(ROOT, 'doc/screenshot');
const TMP_OUTPUT = path.join(OUTPUT, '.tmp');
const MERGE = process.argv.includes('--merge');

const walk = async (directory) => {
    const entries = await fs.readdir(directory, {withFileTypes: true});
    const files = await Promise.all(entries.map(entry => {
        const full = path.join(directory, entry.name);
        return entry.isDirectory() ? walk(full) : Promise.resolve([full]);
    }));
    return files.flat();
};

const main = async () => {
    let scopes = [];
    try {
        scopes = await walk(TMP_OUTPUT);
    } catch {
        console.log('No screenshots captured; nothing to index');
        return;
    }

    const sidecars = scopes.filter(file => file.endsWith('.json') && !file.endsWith('manifest.json'));
    const freshManifests = [];
    for (const sidecar of sidecars) {
        const parsed = JSON.parse(await fs.readFile(sidecar, 'utf8'));
        freshManifests.push(parsed);
    }

    let manifests = freshManifests;
    if (MERGE) {
        const previous = JSON.parse(await fs.readFile(path.join(OUTPUT, 'manifest.json'), 'utf8').catch(() => '[]'));
        const merged = new Map(previous.map(entry => [entry.file, entry]));
        for (const entry of freshManifests) merged.set(entry.file, entry);
        manifests = [...merged.values()];

        for (const file of scopes) {
            const relative = path.relative(TMP_OUTPUT, file);
            if (relative.endsWith('.json')) continue;
            const destination = path.join(OUTPUT, relative);
            await fs.mkdir(path.dirname(destination), {recursive: true});
            await fs.copyFile(file, destination);
        }
    }

    manifests.sort((a, b) => a.file.localeCompare(b.file));

    const gallery = manifests
        .map(entry => {
            const title = `${entry.area} / ${entry.state}`;
            return `### ${title}\n\n${entry.description}\n\n![${title}](${entry.file})\n`;
        })
        .join('\n');

    const readme = [
        '# Screenshots',
        '',
        'Generated by `pnpm screenshots` (all) or `pnpm screenshot <group>` (one area). Set `SCREENSHOT_WORKERS` to change parallelism (defaults to the machine CPU count, capped at 8). These images demonstrate what the system can do; they are not test baselines.',
        '',
        `${manifests.length} images.`,
        '',
        gallery,
    ].join('\n');

    if (MERGE) {
        await fs.writeFile(path.join(OUTPUT, 'README.md'), readme);
        await fs.writeFile(path.join(OUTPUT, 'manifest.json'), JSON.stringify(manifests, null, 2));
        await fs.rm(TMP_OUTPUT, {recursive: true, force: true});
        console.log(`Updated ${freshManifests.length} screenshots; gallery has ${manifests.length}`);
        return;
    }

    for (const sidecar of sidecars) {
        await fs.rm(sidecar);
    }

    // Write index files to .tmp first
    await fs.writeFile(path.join(TMP_OUTPUT, 'README.md'), readme);
    await fs.writeFile(path.join(TMP_OUTPUT, 'manifest.json'), JSON.stringify(manifests, null, 2));
    console.log(`Wrote index for ${manifests.length} screenshots`);

    // Atomic swap: rename .tmp to a temp name outside OUTPUT, remove old OUTPUT, then move into place
    const SWAP_OUTPUT = path.join(ROOT, 'doc/screenshot.swap');
    const ARCHIVE = path.join(OUTPUT, 'archive');
    const ARCHIVE_SWAP = path.join(SWAP_OUTPUT, 'archive');
    await fs.rm(SWAP_OUTPUT, {recursive: true, force: true});
    await fs.rename(TMP_OUTPUT, SWAP_OUTPUT);
    if (await fs.stat(ARCHIVE).then(() => true).catch(() => false)) {
        await fs.cp(ARCHIVE, ARCHIVE_SWAP, {recursive: true});
    }
    await fs.rm(OUTPUT, {recursive: true, force: true});
    await fs.rename(SWAP_OUTPUT, OUTPUT);
    console.log('Gallery swapped successfully');
};

main();
